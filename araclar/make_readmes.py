TR_ALPHA = 'abcçdefgğhıijklmnoöprsştuüvwxyz'


def tr_lower(s):
    return s.replace('I', 'ı').replace('İ', 'i').lower()


def tr_key(s):
    return tuple(TR_ALPHA.index(ch) if ch in TR_ALPHA else 100 + ord(ch) for ch in tr_lower(s))


_FOLD = str.maketrans('çğıöşüâîû', 'cgiosuaiu')
CODE_RE = re.compile(r'(?i)(?<![a-z])(elm|elec|ec|eem|mat|math|fiz|phys|inf|mbm|bil|tur|tür)[-_ ]?\d{3}(?!\d)')


def natkey(name):
    """Natural sort key: first number (lecture/week no.), then word/number tokens."""
    base = name.lower()
    m = re.search(r'\d+', CODE_RE.sub(' ', base))
    first = int(m.group()) if m else None
    toks = []
    for t in re.findall(r'\d+|[^\W\d_]+', base):
        toks.append((0, int(t), '') if t.isdigit() else (1, 0, t.translate(_FOLD)))
    return (first is None, first or 0, tuple(toks), base)


def md(s):
    """Escape text for Markdown (also safe inside table cells)."""
    s = str(s).replace('\\', '\\\\')
    for ch in '`*_[]<>|':
        s = s.replace(ch, '\\' + ch)
    return s


def url(rel):
    """Percent-encode a relative POSIX path for a Markdown link."""
    trail = '/' if rel.endswith('/') else ''
    segs = [s for s in rel.split('/') if s != '']
    return '/'.join(urllib.parse.quote(s, safe='') for s in segs) + trail


def mlink(text, rel, anchor=None):
    tgt = url(rel)
    if anchor:
        tgt += '#' + urllib.parse.quote(anchor, safe='-_')
    return '[%s](%s)' % (text, tgt)


def code_link(name, rel):
    if '`' in name or '|' in name:
        return mlink(md(name), rel)
    return mlink('`%s`' % name, rel)


def gh_slug(text):
    """GitHub heading anchor (github-slugger behaviour for the headings used here)."""
    t = re.sub(r'\[([^\]]*)\]\([^)]*\)', r'\1', text)
    t = t.strip().lower()
    t = re.sub(r'[^\w\- ]', '', t)
    return t.replace(' ', '-')


def pretty(stem):
    """'Isaret-ve-Sistemler-ders-8-10' -> 'Isaret ve Sistemler ders 8-10'."""
    s = re.sub(r'(?<=\d)-(?=\d)', '\x00', stem)
    s = re.sub(r'[-_]+', ' ', s).replace('\x00', '-')
    s = re.sub(r'\s+', ' ', s).strip()
    return s or stem


