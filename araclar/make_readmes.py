def render_projects_section(c):
    L = []
    for u in c.projects:
        L += ['### ' + md(u.title_tr), '']
        meta = []
        if u.title_en and u.title_en != u.title_tr:
            meta.append('*%s*' % md(u.title_en))
        if u.path:
            meta.append('Klasör: ' + mlink('`%s/`' % u.path, u.path + '/'))
        for r in u.repos:
            meta.append('GitHub: [%s](%s)' % (md(r['name']), repo_url(r)))
        if meta:
            L += [' · '.join(meta), '']
        if u.files:
            loose, groups = [], {}
            base = u.path or ''
            for f in u.files:
                sub = f.rel[len(base) + 1:] if base and f.rel.startswith(base + '/') else f.rel
                if '/' in sub:
                    g = (base + '/' if base else '') + sub.split('/', 1)[0]
                    groups.setdefault(g, []).append(f)
                else:
                    loose.append(f)
            if loose:
                L += loose_table(loose, base) + ['']
            if groups:
                L += group_table(groups) + ['']
        elif u.repos:
            L += ['Bu projenin dosyaları GitHub deposundadır: ' +
                  ', '.join('[%s](%s)' % (md(r['name']), repo_url(r)) for r in u.repos) +
                  ('. ' + md(u.repos[0].get('description_tr', '')) if u.repos[0].get('description_tr') else ''), '']
    return L


