AUTO_IMG_RE = re.compile(r'^(img|whatsapp|screenshot|ekran|tmp_|pxl_|dsc|photo|image[-_]?\d)|^\d{6,}', re.I)


def file_info(f, lang='tr'):
    bits = []
    if f.ext == 'pdf' and f.pages:
        bits.append('%d %s' % (f.pages, 's.' if lang == 'tr' else 'p.'))
    if f.size >= BIG_FILE:
        bits.append(human_size(f.size, lang))
