def classify_dir(name, is_lab):
    n = name.lower()
    if n in CANON_DIRS:
        return CANON_DIRS[n]
    if LAB_UNIT_RE.match(n):
        return 'laboratuvar' if (is_lab or n != 'final') else 'sinav-calismasi'
    if re.match(r'(final|vize|sinav|ara-sinav)[-_]', n):
        return 'sinav-calismasi'
    if re.match(r'(odev|hw)[-_]?\d+', n):
        return 'odevler'
    if re.match(r'proje[-_]?\d+', n):
        return 'projeler'
    return 'diger'


