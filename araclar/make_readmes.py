def badge(label, value, color):
    q = lambda s: urllib.parse.quote(s.replace('-', '--').replace('_', '__'), safe='')
    return '![%s: %s](https://img.shields.io/badge/%s-%s-%s)' % (label, value, q(label), q(str(value)), color)


def all_projects(R):
    rows = []
    for c in R.courses:
        for u in c.projects:
            rows.append((c, u))
    return rows


def code_repos(R):
    """Non-project repos -> [(repo dict, [courses])], merged by repo name."""
    out, idx = [], {}
    for c in R.courses:
        for r in c.meta.get('repos') or []:
            if r.get('kind') == 'project':
                continue
            if r['name'] in idx:
                out[idx[r['name']]][1].append(c)
            else:
                idx[r['name']] = len(out)
                out.append((r, [c]))
    return out


