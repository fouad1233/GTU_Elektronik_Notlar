class Course:
    def __init__(self, R, sem, dirname, meta):
        self.R, self.sem, self.dirname = R, sem, dirname
        self.key = '%d-Donem/%s' % (sem, dirname)
        self.dir = os.path.join(R.repo, '%d-Donem' % sem, dirname)
        self.meta = meta or {}
        if not meta:
            warn('courses.json has no entry for %s (name derived from the folder name)' % self.key)
        self.name_tr = self.meta.get('name_tr') or pretty(dirname)
        self.name_en = self.meta.get('name_en') or self.name_tr
        self.code = self.meta.get('code')
        self.desc_tr = self.meta.get('description_tr') or ''
        self.desc_en = self.meta.get('description_en') or ''
        self.is_lab = bool(re.search(r'(?i)lab', dirname))
        self.files, self.sections, self.digital, self.digital_pending = [], {}, [], []
        self.projects, self.counts = [], {}

    # ---- scanning ------------------------------------------------------------------------
    def scan(self, ign):
        out = []
        for dp, dns, fns in os.walk(self.dir):
            dns[:] = sorted(d for d in dns if not ign.skip_dir(d))
            for fn in sorted(fns):
                rel = os.path.relpath(os.path.join(dp, fn), self.dir).replace(os.sep, '/')
                if ign.skip_file(fn, rel):
                    continue
                if fn == 'README.md':
                    if rel == 'README.md' or is_generated(os.path.join(dp, fn)):
                        continue
                try:
                    out.append(FileInfo(self.dir, self.R.repo, rel))
                except OSError:
                    continue            # vanished while scanning (other workers)
        self.files = out

    def classify(self):
        overrides = dict(self.meta.get('sections') or {})
        for k, v in overrides.items():
            if v not in CAT:
                warn('%s: unknown category %r in "sections" for %s' % (self.key, v, k))
        for f in self.files:
            if f.top == '':
                cat = classify_root_file(f.name, self.is_lab)
                cat = overrides.get(f.name, cat)
            else:
                cat = classify_dir(f.top, self.is_lab)
                cat = overrides.get(f.top, cat)
            f.cat = cat if cat in CAT else 'diger'
        for f in self.files:
            self.sections.setdefault(f.cat, []).append(f)

    # ---- grouping ------------------------------------------------------------------------
    def split_section(self, files):
        """-> (loose files, {group path: [files]}) ; group path is relative to the course."""
        loose, groups = [], {}
        for f in files:
            parts = f.rel.split('/')
            if len(parts) == 1:
                loose.append(f)
            elif is_unit_dir(parts[0]):
                groups.setdefault(parts[0], []).append(f)
            elif len(parts) == 2:
                loose.append(f)
            else:
                groups.setdefault(parts[0] + '/' + parts[1], []).append(f)
        return loose, groups

    # ---- digital notes -------------------------------------------------------------------
    def build_digital(self):
        by_stem = {}
        for f in self.sections.get('dijital-notlar', []):
            if f.ext in ('pdf', 'tex') and '/' not in f.rel[len(f.top) + 1:]:
                d = by_stem.setdefault(f.stem, DigitalNote(f.stem))
                setattr(d, f.ext, f)
        cands = [f for f in self.files if f.cat != 'dijital-notlar']
        for stem in sorted(by_stem, key=natkey):
            d = by_stem[stem]
            complete = True
            if d.tex:
                try:
                    text = open(d.tex.abs, encoding='utf-8', errors='replace').read(400000)
                except OSError:
                    text = ''
                d.info = parse_notbilgi(text)
                complete = '\\end{document}' in strip_tex_comments(text)
                if d.info is None:
                    warn('%s: no \\notbilgi in %s' % (self.key, d.tex.rel))
            if d.pdf is None or not complete:
                # not compiled yet / still being written by another worker: listed once the PDF exists
                self.digital_pending.append(d.tex.rel if d.tex else d.stem)
                continue
            d.source = resolve_source(cands, d.info['source'] if d.info else None, stem)
            if d.source is None:
                warn('%s: could not find the original note for %s (source %r)'
                     % (self.key, stem, d.info['source'] if d.info else None))
            self.digital.append(d)
        self.digital.sort(key=lambda d: ((CAT[d.source.cat]['idx'], natkey(d.source.name), d.source.rel)
                                         if d.source else (99, natkey(''), ''), natkey(d.stem)))

    def digital_by_source(self):
        m = {}
        for d in self.digital:
            if d.source is not None and d.pdf is not None:
                m.setdefault(d.source.rel, []).append(d)
        return m

    # ---- projects ------------------------------------------------------------------------
    def build_projects(self):
        mapping = self.meta.get('projects') or {}
        units, by_path = [], {}
        for path, t in mapping.items():
            u = ProjectUnit(path.strip('/'), t.get('tr') or pretty(path), t.get('en') or t.get('tr') or pretty(path))
            units.append(u)
            by_path[u.path] = u
        for f in self.sections.get('projeler', []):
            best = None
            for p, u in by_path.items():
                if (f.rel == p or f.rel.startswith(p + '/')) and (best is None or len(p) > len(best.path)):
                    best = u
            if best is None:
                parts = f.rel.split('/')
                p = '/'.join(parts[:2]) if (len(parts) >= 3 and not is_unit_dir(parts[0])) else parts[0]
                if p not in by_path:
                    lbl = folder_label(p.rsplit('/', 1)[-1]) if '/' in p or is_unit_dir(p) else 'Proje'
                    u = ProjectUnit(p, lbl, lbl, auto=True)
                    units.append(u)
                    by_path[p] = u
                    warn('%s: project folder %s has no title in courses.json' % (self.key, p))
                best = by_path[p]
            best.files.append(f)
        for r in self.meta.get('repos') or []:
            if r.get('kind') != 'project':
                continue
            p = (r.get('project') or '').strip('/')
            if p and p in by_path:
                by_path[p].repos.append(r)
            else:
                u = ProjectUnit(None, r.get('title_tr') or r['name'], r.get('title_en') or r.get('title_tr') or r['name'])
                u.repos.append(r)
                units.append(u)
        for u in units:
            if u.path and not u.files and not u.repos:
                warn('%s: project folder %s from courses.json not found' % (self.key, u.path))
        self.projects = sorted([u for u in units if u.files or u.repos],
                               key=lambda u: (u.path is None, natkey(u.path or ''), u.title_tr))

    # ---- counts --------------------------------------------------------------------------
    def build_counts(self):
        for cat, files in self.sections.items():
            if cat in ('genel', 'dijital-notlar', 'projeler'):
                continue
            if cat == 'kod':
                self.counts[cat] = len(files)
                continue
            loose, groups = self.split_section(files)
            if cat == 'laboratuvar':
                n = sum(1 for g in groups if LAB_UNIT_RE.match(g.rsplit('/', 1)[-1]))
                if n:
                    self.counts[cat] = n
                    continue
                docs = [f for g in groups.values() for f in g if f.kind == 'doc']
                n = len(docs) + count_units(loose, {})
                self.counts[cat] = n or len(files)
                continue
            self.counts[cat] = count_units(loose, groups) or len(files)
        n_dig = sum(1 for d in self.digital if d.pdf is not None)
        if n_dig:
            self.counts['dijital-notlar'] = n_dig
        if self.projects:
            self.counts['projeler'] = len(self.projects)

    def build(self, ign):
        self.scan(ign)
        self.classify()

    def finish(self):
        self.build_digital()
        self.build_projects()
        self.build_counts()


def count_units(loose, groups):
    docs = sum(1 for f in loose if f.kind == 'doc')
    img_dirs = {f.rel.rsplit('/', 1)[0] if '/' in f.rel else '' for f in loose if f.kind == 'img'}
    return len(groups) + docs + len(img_dirs)


def resolve_source(cands, src, stem):
    def pick(ms):
        if len(ms) == 1:
            return ms[0]
        for f in ms:
            if f.top and stem.lower().startswith(f.top.lower() + '-'):
                return f
        return sorted(ms, key=lambda f: (CAT[f.cat]['idx'], natkey(f.rel)))[0]
    if src:
        src = src.strip().replace('\\', '/')
        base = src.rsplit('/', 1)[-1]
        for test in (lambda f: f.rel == src, lambda f: f.name == base, lambda f: f.name.lower() == base.lower()):
            ms = [f for f in cands if test(f)]
            if ms:
                return pick(ms)
    base, top = stem, None
    for t in sorted({f.top for f in cands if f.top}, key=len, reverse=True):
        if stem.lower().startswith(t.lower() + '-'):
            base, top = stem[len(t) + 1:], t
            break
    for b in (base, re.sub(r'[-_]\d{1,2}$', '', base)):
        ms = [f for f in cands if f.stem == b and (top is None or f.top == top)] or \
             [f for f in cands if f.stem.lower() == b.lower()]
        if ms:
            return pick(ms)
    return None


def is_generated(path):
    try:
        with open(path, encoding='utf-8', errors='replace') as fh:
            return MARKER in fh.read(4000)
    except OSError:
        return False


class Repo:
    def __init__(self, repo, meta, pages):
        self.repo, self.meta, self.pages = repo, meta, pages
        self.semesters = {}            # sem -> [Course]
        self.courses = []
        self.ign = Ignore(repo)
        self.gh_user = meta.get('github_user', 'fouad1233')
        self.slug = meta.get('repo_slug', 'fouad1233/GTU_Elektronik_Notlar')
        self.terms = meta.get('semesters', {})

    def scan(self):
        cmeta = self.meta.get('courses', {})
        for d in sorted(os.listdir(self.repo)):
            m = re.fullmatch(r'(\d+)-Donem', d)
            if not m or not os.path.isdir(os.path.join(self.repo, d)):
                continue
            sem = int(m.group(1))
            lst = []
            for cd in sorted(os.listdir(os.path.join(self.repo, d))):
                if cd.startswith('.') or not os.path.isdir(os.path.join(self.repo, d, cd)):
                    continue
                c = Course(self, sem, cd, cmeta.get('%s/%s' % (d, cd)))
                c.build(self.ign)
                lst.append(c)
            lst.sort(key=lambda c: tr_key(c.name_tr))
            self.semesters[sem] = lst
            self.courses.extend(lst)
        for k in cmeta:
            if not os.path.isdir(os.path.join(self.repo, k)):
                warn('courses.json entry %s has no folder in the repo' % k)
        pdfs = [f for c in self.courses for f in c.files if f.ext == 'pdf']
        sab = os.path.join(self.repo, 'latex-sablon', 'ornek.pdf')
        self.sablon_pdf = None
        if os.path.exists(sab):
            self.sablon_pdf = FileInfo(os.path.join(self.repo, 'latex-sablon'), self.repo, 'ornek.pdf')
            pdfs.append(self.sablon_pdf)
        self.pages.fill(pdfs)
        for c in self.courses:
            c.finish()

    def term(self, sem, lang):
        t = self.terms.get(str(sem), {})
        return t.get('term_tr' if lang == 'tr' else 'term_en', '')


