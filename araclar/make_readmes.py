def latex_to_text(s):
    if not s:
        return ''
    s = s.replace('---', '—').replace('--', '–')
    s = re.sub(r'(?<!\\)~', ' ', s)
    s = re.sub(r'\\[,;: !]', ' ', s)
    s = re.sub(r'\\mathcal\s*\{\s*L\s*\}', 'ℒ', s)
    s = re.sub(r'\\mathcal\s*\{\s*F\s*\}', 'ℱ', s)
    for k in sorted(TEX_SYMBOLS, key=len, reverse=True):
        pat = re.escape(k) + (r'(?![A-Za-z])' if k[-1].isalpha() else '')
        s = re.sub(pat, lambda m, v=TEX_SYMBOLS[k]: v, s)
    prev = None
    while prev != s:
        prev = s
        s = re.sub(r'\\[A-Za-z]+\*?\s*(?:\[[^\]]*\])?\s*\{([^{}]*)\}', r'\1', s)
    s = re.sub(r'\\[A-Za-z]+\*?', '', s)
    s = s.replace('$', '').replace('{', '').replace('}', '')
    return re.sub(r'\s+', ' ', s).strip()


def strip_tex_comments(text):
    out = []
    for line in text.splitlines():
        m = re.search(r'(?<!\\)%', line)
        out.append(line[:m.start()] if m else line)
    return '\n'.join(out)


def _read_group(t, k, op, cl):
    """t[k] == op; return (content, index after the closing char) honouring nesting."""
    depth, i, n = 0, k, len(t)
    while i < n:
        c = t[i]
        if c == '\\':
            i += 2
            continue
        if c == op:
            depth += 1
        elif c == cl:
            depth -= 1
            if depth == 0:
                return t[k + 1:i], i + 1
        elif op == '[' and c == '{':
            _, i = _read_group(t, i, '{', '}')
            continue
        i += 1
    return None, n


def parse_notbilgi(text):
    """Return dict(opt, course, topic, source) from the first \\notbilgi[..]{..}{..}{..}."""
    t = strip_tex_comments(text)
    for m in re.finditer(r'\\notbilgi(?![A-Za-z])', t):
        k = m.end()
        opt = None
        while k < len(t) and t[k].isspace():
            k += 1
        if k < len(t) and t[k] == '[':
            opt, k = _read_group(t, k, '[', ']')
        args = []
        for _ in range(3):
            while k < len(t) and t[k].isspace():
                k += 1
            if k >= len(t) or t[k] != '{':
                break
            a, k = _read_group(t, k, '{', '}')
            if a is None:
                break
            args.append(a)
        if len(args) == 3:
            return {'opt': opt, 'course': args[0].strip(), 'topic': args[1].strip(), 'source': args[2].strip()}
    return None


