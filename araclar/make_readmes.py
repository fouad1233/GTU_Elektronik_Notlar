def main(argv=None):
    ap = argparse.ArgumentParser(description='Generate the README.md files of GTU_Elektronik_Notlar.')
    ap.add_argument('--repo', default=DEFAULT_REPO)
    ap.add_argument('--courses', default=DEFAULT_COURSES)
    ap.add_argument('--cache', default=DEFAULT_CACHE)
    ap.add_argument('--no-pdfinfo', action='store_true', help='do not run pdfinfo (use cached page counts only)')
    ap.add_argument('--dry-run', action='store_true', help='render and check, but do not write')
    ap.add_argument('--check-only', action='store_true', help='only check links of existing generated READMEs')
    ap.add_argument('--force', action='store_true', help='overwrite README.md files without the generator marker')
    ap.add_argument('-q', '--quiet', action='store_true')
    a = ap.parse_args(argv)

    repo = os.path.abspath(a.repo)
    if not os.path.isdir(repo):
        print('repo not found: %s' % repo, file=sys.stderr)
        return 2
    try:
        meta = json.load(open(a.courses, encoding='utf-8'))
    except (OSError, ValueError) as e:
        print('cannot read %s: %s' % (a.courses, e), file=sys.stderr)
        return 2

    if a.check_only:
        mds = []
        for dp, dns, fns in os.walk(repo):
            dns[:] = [d for d in dns if not d.startswith('.')]
            if 'README.md' in fns and is_generated(os.path.join(dp, 'README.md')):
                mds.append(os.path.relpath(os.path.join(dp, 'README.md'), repo))
        problems, n = check_links(repo, sorted(mds))
        for pr in problems:
            print('BROKEN ' + pr)
        print('checked %d links in %d READMEs: %d problem(s)' % (n, len(mds), len(problems)))
        return 1 if problems else 0

    pages = PageCounter(a.cache, enabled=not a.no_pdfinfo)
    R = Repo(repo, meta, pages)
    R.scan()
    pages.save()

    outputs = {'README.md': render_main(R)}
    for sem in sorted(R.semesters):
        outputs['%d-Donem/README.md' % sem] = render_semester(R, sem)
        for c in R.semesters[sem]:
            outputs[c.key + '/README.md'] = render_course(R, c)
    if os.path.isdir(os.path.join(repo, 'latex-sablon')):
        outputs['latex-sablon/README.md'] = render_sablon(R)

    written, unchanged, skipped = write_outputs(repo, outputs, force=a.force, dry=a.dry_run)
    problems, n_links = ([], 0) if a.dry_run else check_links(repo, sorted(set(written + unchanged)))

    pending = [(c.key, t) for c in R.courses for t in c.digital_pending]
    if not a.quiet:
        print('courses: %d  files: %d  digital notes: %d (+%d in progress)  projects: %d'
              % (len(R.courses), sum(len(c.files) for c in R.courses),
                 sum(c.counts.get('dijital-notlar', 0) for c in R.courses), len(pending),
                 sum(len(c.projects) for c in R.courses)))
        print('READMEs: %d written, %d unchanged, %d skipped (no generator marker; use --force)%s'
              % (len(written), len(unchanged), len(skipped), ' [dry run]' if a.dry_run else ''))
        for s in skipped:
            print('  skipped: ' + s)
        if pending:
            print('digital notes still in progress (.tex without PDF / \\end{document}), not listed yet:')
            for k, t in pending:
                print('  %s/%s' % (k, t))
        for w in WARNINGS:
            print('WARNING: ' + w)
        if not a.dry_run:
            print('link check: %d links, %d problem(s)' % (n_links, len(problems)))
    for pr in problems:
        print('BROKEN ' + pr)
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main())
