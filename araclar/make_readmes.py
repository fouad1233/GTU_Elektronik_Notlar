# PDF page counts (pdfinfo, cached)
# --------------------------------------------------------------------------------------------
class PageCounter:
    def __init__(self, cache_path, enabled=True):
        self.cache_path = cache_path
        self.enabled = enabled and shutil.which('pdfinfo') is not None
        self.cache, self.seen, self.dirty = {}, set(), False
        if cache_path and os.path.exists(cache_path):
            try:
                self.cache = json.load(open(cache_path, encoding='utf-8'))
            except (OSError, ValueError):
                self.cache = {}

    def _run(self, path):
        try:
            r = subprocess.run(['pdfinfo', path], capture_output=True, timeout=90)
            m = re.search(rb'^Pages:\s+(\d+)', r.stdout, re.M)
            return int(m.group(1)) if m else None
        except (OSError, subprocess.SubprocessError):
            return None

    def fill(self, files):
        """files: FileInfo list (pdf); sets f.pages."""
        todo = []
        for f in files:
            self.seen.add(f.repo_rel)
            c = self.cache.get(f.repo_rel)
            if c and c[0] == f.size and c[1] == f.mtime and c[2]:
                f.pages = c[2]
            elif self.enabled:
                todo.append(f)
        if todo:
            with ThreadPoolExecutor(max_workers=3) as ex:
                for f, n in zip(todo, ex.map(lambda x: self._run(x.abs), todo)):
                    f.pages = n
                    if n:
                        self.cache[f.repo_rel] = [f.size, f.mtime, n]
                        self.dirty = True

    def save(self):
        stale = [k for k in self.cache if k not in self.seen]
        for k in stale:
            del self.cache[k]
        if (self.dirty or stale) and self.cache_path:
            tmp = self.cache_path + '.tmp'
            with open(tmp, 'w', encoding='utf-8') as fh:
                json.dump(self.cache, fh, ensure_ascii=False, sort_keys=True)
            os.replace(tmp, self.cache_path)


