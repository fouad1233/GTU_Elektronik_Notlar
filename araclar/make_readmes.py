def write_outputs(repo, outputs, force=False, dry=False):
    written, unchanged, skipped = [], [], []
    for rel in sorted(outputs):
        path = os.path.join(repo, rel)
        content = outputs[rel]
        if not content.endswith('\n'):
            content += '\n'
        if os.path.exists(path):
            try:
                old = open(path, encoding='utf-8').read()
            except OSError:
                old = None
            if old is not None and MARKER not in old and not force:
                skipped.append(rel)
                continue
            if old == content:
                unchanged.append(rel)
                continue
        if not dry:
            tmp = path + '.make_readmes.tmp'
            with open(tmp, 'w', encoding='utf-8') as fh:
                fh.write(content)
            os.replace(tmp, path)
        written.append(rel)
    return written, unchanged, skipped


LINK_RE = re.compile(r'\]\(([^)\s]+)\)')


def heading_slugs(text):
    slugs, seen, fence = set(), {}, False
    for line in text.splitlines():
        if line.lstrip().startswith('```'):
            fence = not fence
            continue
        if fence:
            continue
        m = re.match(r'^(#{1,6})\s+(.*?)\s*#*\s*$', line)
        if m:
            s = gh_slug(m.group(2))
            if s in seen:
                seen[s] += 1
                s = '%s-%d' % (s, seen[s])
            else:
                seen[s] = 0
            slugs.add(s)
    return slugs


def check_links(repo, md_files):
    problems, n_links = [], 0
    slug_cache = {}

    def slugs_of(p):
        if p not in slug_cache:
            try:
                slug_cache[p] = heading_slugs(open(p, encoding='utf-8').read())
            except OSError:
                slug_cache[p] = set()
        return slug_cache[p]

    for rel in md_files:
        p = os.path.join(repo, rel)
        if not os.path.exists(p):
            continue
        text = open(p, encoding='utf-8').read()
        # drop fenced code blocks and inline code spans before scanning links
        body = re.sub(r'```.*?```', '', text, flags=re.S)
        for m in LINK_RE.finditer(body):
            tgt = m.group(1)
            n_links += 1
            if re.match(r'^[a-z][a-z0-9+.-]*:', tgt, re.I):
                continue                                    # http(s), mailto …
            path_part, _, anchor = tgt.partition('#')
            if path_part:
                dest = os.path.normpath(os.path.join(os.path.dirname(p), urllib.parse.unquote(path_part)))
                if not dest.startswith(os.path.normpath(repo)):
                    problems.append('%s: link leaves the repo: %s' % (rel, tgt))
                    continue
                if not os.path.exists(dest):
                    problems.append('%s: missing target: %s' % (rel, tgt))
                    continue
            else:
                dest = p
            if anchor:
                md_dest = os.path.join(dest, 'README.md') if os.path.isdir(dest) else dest
                if md_dest.endswith('.md') and urllib.parse.unquote(anchor) not in slugs_of(md_dest):
                    problems.append('%s: missing anchor: %s' % (rel, tgt))
    return problems, n_links


