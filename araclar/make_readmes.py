    multi_cat = len({d.source.cat for d in c.digital if d.source}) > 1
    L += ['| Orijinal not | Konu | Dijital PDF | LaTeX kaynağı |', '|---|---|---|---|']
    for d in c.digital:
        if d.source:
            src = doc_text(d.source, d.source.top) if d.source.top else doc_text(d.source)
            if multi_cat:
                src += ' <sub>%s</sub>' % CAT[d.source.cat]['tr']
        else:
            src = '—'
        if d.pdf:
            pdf = mlink('PDF', d.pdf.rel) + ((' · %d s.' % d.pdf.pages) if d.pdf.pages else '')
        else:
            pdf = '—'
        tex = mlink('.tex', d.tex.rel) if d.tex else '—'
        L.append('| %s | %s | %s | %s |' % (src, md(d.topic) or '—', pdf, tex))
    L.append('')
