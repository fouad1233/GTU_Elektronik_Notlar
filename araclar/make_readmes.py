class Ignore:
    def __init__(self, repo):
        self.file_pats, self.dir_pats, self.path_pats = [], [], []
        p = os.path.join(repo, '.gitignore')
        if os.path.exists(p):
            for line in open(p, encoding='utf-8', errors='replace'):
                line = line.strip()
                if not line or line.startswith('#') or line.startswith('!'):
                    continue
                if line.endswith('/'):
                    self.dir_pats.append(line.rstrip('/').lstrip('/'))
                elif '/' in line.strip('/'):
                    self.path_pats.append(line.lstrip('/'))
                else:
                    self.file_pats.append(line.lstrip('/'))
                    self.dir_pats.append(line.lstrip('/'))

    def skip_dir(self, name):
        return name.startswith('.') or any(fnmatch(name, p) for p in self.dir_pats)

    def skip_file(self, name, rel):
        return (name.startswith('.') or any(fnmatch(name, p) for p in self.file_pats)
                or any(fnmatch(rel, p) for p in self.path_pats))


